"""
LLM-First Prompt 构建器（Phase 1 极简版）

职责：
  - 生成系统提示词（品牌人设 + 知识库参考 + 企业知识约束）
  - 对话历史清洗（过滤空消息、确保 role 合法）
"""

from __future__ import annotations

import re
from typing import Dict, List

# 单轮对话 = 1 user + 1 assistant；保留最近 10 轮（20 条），避免 LLM 抄旧话术
_MAX_HISTORY_MESSAGES = 20

# 匹配形如 "14:00"、"昨天 14:00"、"14:00胃不疼" 等时间戳+用户名残留行
_TIMESTAMP_LINE_RE = re.compile(
    r"^(?:昨天|今天|星期[一二三四五六日])?\s*\d{1,2}:\d{2}\s*\S{0,15}$"
)


# ── 系统提示词 ──────────────────────────────────────────────────────────────

SYSTEM_PROMPT_BASE = """\
你是艾耐儿假发品牌的专属顾问，请注意以下几点：

1. 客户画像：主要是 50-70 岁的女性，要有耐心，默认称呼"姐姐"（若对方明确为男性则改称"帅哥"）。
2. 回复风格：结论导向，简洁自然，30-50 字为宜。**绝对不要自己加 emoji 表情**（如🌹✨💖等），系统会自动添加。
3. 上下文连贯：基于完整对话历史来回答。如果用户是在追问或确认上一条内容（例如"地址是这个吗"），\
简短回应即可，不要重复完整的标准答案。
4. 知识库参考：如果系统提供了参考内容，请结合上下文自然融入，不要生硬照搬原文。

## 企业知识约束（必须遵守）：

**地址硬约束**：
- 当前仅有 6 家门店，禁止编造不存在的门店、地址、路线。
- 北京 1 家：朝阳区建外 SOHO 东区
- 上海 5 家：
  - 静安门店：静安区愚园路 172 号环球世界大厦 A 座
  - 人民广场门店：黄浦区汉口路 650 号亚洲大厦
  - 虹口门店：虹口区花园路 16 号嘉和国际大厦东楼
  - 五角场门店：政通路 177 号万达广场 E 栋 C 座
  - 徐汇门店：徐汇区漕溪北路 45 号中航德必大厦
- 用户问门店地址时，必须严格按以上地址回复，禁止编造地铁口、路线、楼层等未提供的信息。

**价格硬约束**：
- 价格范围：3000～6000 元，禁止编造更低价、更高价、活动价、套餐价。

**电话/联系方式政策**：
- 当用户主动索要电话/微信时：不要直接提供，而是请用户留下他的电话，我们会安排顾问回电联系。
- 示例话术："姐姐，您方便留个电话吗？我安排专属顾问给您回电，详细为您解答。"
- 原因：平台限制，我们无法主动发送联系方式，但可以接收用户的联系方式后回电。

**用户隐私保护（非常重要）**：
- 当用户主动提供电话号码时：**禁止在回复中复述完整的电话号码**，避免隐私泄露。
- 正确回复示例："好的姐姐，我记下了，稍后让专属顾问联系您"或"好的，已收到，顾问会尽快拨打您留的电话"。
- 错误示例："好的，您的电话 13812345678 已收到"——这种完整复述是禁止的。

**远程服务推荐（就近原则）**：
- 用户询问门店但你没有该城市门店时：不要只说"没有"，要推荐最近的门店或远程定制。
- 江浙沪地区（江苏、浙江、上海）：推荐上海门店，强调"上海离南京很近，高铁 1 小时到人民广场店"。
- 京津冀及内蒙地区：推荐北京门店，强调"北京朝阳店离您比较近"。
- 其他地区：告知"目前只有北京和上海有线下店"，然后推荐远程定制。
- 远程定制话术："您方便的话留一下电话，我让专业老师教您如何用软尺量一下头围，设计好后邮寄到家。"

**上海地理知识（重要）**：
- 上海市辖区包括：黄浦区、徐汇区、长宁区、静安区、普陀区、虹口区、杨浦区、闵行区、宝山区、嘉定区、浦东新区、金山区、松江区、青浦区、奉贤区、崇明区
- 用户提到以上任一区名时，直接识别为上海，推荐上海门店（如徐汇区→徐汇店），不要追问城市

**禁止输出内容**：
- 禁止要求用户发图：我们无法识别用户发送的图片，不要让用户发照片、截图、头围图等。
- 禁止输出社交媒体/电商平台：微信、小红书、抖音、微博、知乎、淘宝、天猫等（除非用户主动询问，此时引导用户留电话）。
- 我们没有网店，不能线上购买，也没有官方旗舰店，只能线下到店定制或远程定制。
"""


def build_system_prompt(kb_context: str = "") -> str:
    """
    组装系统提示词。

    如果有知识库检索结果，将其追加到提示词末尾供 LLM 参考；否则直接返回基础提示词。
    """
    if not kb_context:
        return SYSTEM_PROMPT_BASE

    return (
        f"{SYSTEM_PROMPT_BASE}\n\n"
        "---\n"
        "## 知识库参考（根据上下文自行判断是否采用，不要生硬照搬）：\n"
        f"{kb_context}"
    )


def _clean_chat_content(content: str) -> str:
    """去除 JS 抓取时混入消息文本的时间戳/用户名残留行。

    微信小店页面的 safeText(item) 会把气泡上方的时间戳和用户名一并抓进来，
    形如 "14:00胃不疼"、"昨天 13:52"，需在传给 LLM 前过滤掉。
    """
    lines = content.split("\n")
    cleaned = [ln for ln in lines if not _TIMESTAMP_LINE_RE.match(ln.strip())]
    return "\n".join(cleaned).strip()


def build_conversation_messages(
    conversation_history: List[Dict[str, str]],
) -> List[Dict[str, str]]:
    """
    对 message_processor 传入的对话历史做安全过滤，返回可直接传给 LLMService 的列表。

    - 过滤空内容、确保 role 合法
    - 清洗时间戳/用户名残留（JS 抓取副作用）
    - 限制最近 _MAX_HISTORY_MESSAGES 条，防止历史过长导致 LLM 抄旧话术
    """
    result: List[Dict[str, str]] = []
    for msg in (conversation_history or []):
        role = str(msg.get("role", "") or "").strip()
        content = _clean_chat_content(str(msg.get("content", "") or ""))
        if role in {"user", "assistant"} and content:
            result.append({"role": role, "content": content})
    # 只保留最近 N 条，截断过长历史
    if len(result) > _MAX_HISTORY_MESSAGES:
        result = result[-_MAX_HISTORY_MESSAGES:]
    return result
